//! Per-player form-regime estimation: fit a 2-state Gaussian HMM on each player's
//! per-90 output series and expose P(hot) as a mean multiplier for event models.
//!
//! Uses the same forward-scaled recursion as quant-fund's factor-primitives HMM
//! (reimplemented locally to keep footy-models dependency-light; identical math:
//! scaled alpha recursion over a 2-state Gaussian emission with fixed priors).
//!
//! As-of discipline: series are precomputed per fixture by scripts/build_form_series.py,
//! strictly before each fixture date.

use footy_forecast::{
    NextMatchParticipationModel, NextMatchPlayerRateModel, PlayerParticipationFeatures,
    PlayerParticipationTrainingExample, PlayerRateFeatures, PlayerRatePrediction,
    PlayerRateTrainingExample,
};
use footy_core::Date;
use std::collections::HashMap;

const RATE_SHOT: u16 = 1;
const RATE_XG: u16 = 2;
const RATE_XA: u16 = 3;
const RATE_PASS: u16 = 4;
const RATE_PROGC: u16 = 5;

/// Empirical-Bayes shrinkage for raw season per-90 rates. Sparse players remain eligible for squad
/// selection without letting a cameo create an extreme event prior. Two full matches of reference
/// exposure is deliberately modest: established players quickly converge toward their observed rate.
pub fn shrunk_player_rate(observed_per90: f64, reference_per90: f64, prior_minutes: f64) -> f64 {
    if !reference_per90.is_finite() || reference_per90 < 0.0 {
        return 0.0;
    }
    let observed = if observed_per90.is_finite() && observed_per90 >= 0.0 {
        observed_per90
    } else {
        reference_per90
    };
    let minutes = if prior_minutes.is_finite() { prior_minutes.max(0.0) } else { 0.0 };
    let weight = minutes / (minutes + 180.0);
    weight * observed + (1.0 - weight) * reference_per90
}

fn parse_iso_date(text: &str) -> Option<Date> {
    let mut parts = text.split('-');
    let year = parts.next()?.parse().ok()?;
    let month = parts.next()?.parse().ok()?;
    let day = parts.next()?.parse().ok()?;
    if parts.next().is_some() { return None; }
    Date::from_ymd(year, month, day).ok()
}

/// Fit the lineup-participation head from rows whose target fixture is strictly before `cutoff`.
/// The TSV is generated by `build_selection_training.py`, which itself excludes cold-start players
/// from their first club listing and counts non-selections only on covered fixtures.
pub fn learned_participation_model_from_tsv(
    text: &str,
    cutoff: Date,
) -> Option<NextMatchParticipationModel> {
    let mut lines = text.lines();
    let header: Vec<&str> = lines.next()?.split('\t').collect();
    let idx = |name: &str| header.iter().position(|value| *value == name);
    let (i_date, i_fixtures, i_listings, i_apps, i_starts, i_minutes, i_start_minutes, i_days, i_days_listed, i_appeared, i_started, i_target_minutes) = (
        idx("date")?,
        idx("club_fixtures")?,
        idx("prior_listings")?,
        idx("prior_appearances")?,
        idx("prior_starts")?,
        idx("prior_minutes")?,
        idx("prior_start_minutes")?,
        idx("days_since_last_appearance")?,
        idx("days_since_last_listed")?,
        idx("appeared")?,
        idx("started")?,
        idx("minutes")?,
    );
    let mut examples = Vec::new();
    for line in lines.filter(|line| !line.trim().is_empty()) {
        let values: Vec<&str> = line.split('\t').collect();
        let Some(target_date) = values.get(i_date).and_then(|value| parse_iso_date(value)) else { continue; };
        if target_date >= cutoff { continue; }
        let parse = |index: usize| -> Option<f64> { values.get(index)?.parse::<f64>().ok() };
        let (Some(club_fixtures), Some(prior_listings), Some(prior_appearances), Some(prior_starts), Some(prior_minutes),
            Some(prior_start_minutes), Some(days_since_last_appearance), Some(days_since_last_listed), Some(appeared), Some(started), Some(minutes)) = (
                parse(i_fixtures), parse(i_listings), parse(i_apps), parse(i_starts), parse(i_minutes), parse(i_start_minutes),
                parse(i_days), parse(i_days_listed), parse(i_appeared), parse(i_started), parse(i_target_minutes),
            ) else { continue; };
        examples.push(PlayerParticipationTrainingExample {
            features: PlayerParticipationFeatures {
                club_fixtures,
                prior_listings,
                prior_appearances,
                prior_starts,
                prior_minutes,
                prior_start_minutes,
                days_since_last_appearance,
                days_since_last_listed,
            },
            appeared: appeared >= 0.5,
            started: started >= 0.5,
            minutes,
        });
    }
    if examples.len() < 100 { return None; }
    NextMatchParticipationModel::fit(&examples, 2.0, 8.0).ok()
}

/// Blended per-90 output: shots weighted 0.5, xG 0.3, xA 0.2 (attacking contribution proxy).
pub fn blend_per90(shots_p90: f64, xg_p90: f64, xa_p90: f64) -> f64 {
    0.5 * shots_p90 + 0.3 * xg_p90 + 0.2 * xa_p90
}

#[derive(Debug, Clone)]
pub struct FormRegime {
    pub p_hot: f64,
    pub hot_mean: f64,
    pub normal_mean: f64,
    pub n_games: usize,
}

impl FormRegime {
    /// Multiplier applied to the player's season-average mean_per90.
    pub fn mean_multiplier(&self) -> f64 {
        if self.n_games < 4 || !self.p_hot.is_finite() {
            return 1.0;
        }
        // P(hot)=1 -> hot/normal ratio, capped; P(hot)=0 -> 1.0.
        let ratio = if self.normal_mean > 1e-6 {
            (self.hot_mean / self.normal_mean).clamp(0.7, 1.35)
        } else {
            1.0
        };
        1.0 + self.p_hot * (ratio - 1.0)
    }
}

/// Fit a simple 2-state Gaussian HMM via EM on one series (scaled forward recursion,
/// a few Baum-Welch-ish iterations). Series must be chronological. Deterministic.
pub fn fit_form_regime(series: &[f64]) -> Option<FormRegime> {
    let n = series.len();
    if n < 4 {
        return None;
    }
    let mean = series.iter().sum::<f64>() / n as f64;
    let var = series.iter().map(|v| (v - mean).powi(2)).sum::<f64>() / (n.max(2) - 1) as f64;
    let sd = var.sqrt().max(1e-6);

    // Init: normal state = full-sample stats, hot state = shifted up by 0.7 sd.
    let mut normal = (mean, sd);
    let mut hot = (mean + 0.7 * sd, sd);
    // Sticky transitions favor regime persistence.
    let trans = [[0.85, 0.15], [0.15, 0.85]];
    let init = [0.8, 0.2];

    let gauss = |x: f64, mu: f64, sigma: f64| -> f64 {
        let z = (x - mu) / sigma;
        (-0.5 * z * z - sigma.ln() - 0.5 * (2.0 * std::f64::consts::PI).ln()).exp()
    };

    let mut p_hot_series = vec![0.0_f64; n];
    for _iter in 0..12 {
        // E-step: scaled forward-backward
        let emit = |t: usize, state: usize| -> f64 {
            let (mu, sigma) = if state == 0 { normal } else { hot };
            gauss(series[t], mu, sigma).max(1e-300)
        };
        let mut alpha = vec![[0.0_f64; 2]; n];
        let mut scales = vec![0.0_f64; n];
        let mut c = init[0] * emit(0, 0) + init[1] * emit(0, 1);
        if !(c.is_finite() && c > 0.0) {
            return None;
        }
        scales[0] = 1.0 / c;
        alpha[0][0] = init[0] * emit(0, 0) * scales[0];
        alpha[0][1] = init[1] * emit(0, 1) * scales[0];
        for t in 1..n {
            c = 0.0;
            for j in 0..2 {
                let a = alpha[t - 1][0] * trans[0][j] + alpha[t - 1][1] * trans[1][j];
                alpha[t][j] = a * emit(t, j);
                c += alpha[t][j];
            }
            if !(c.is_finite() && c > 0.0) {
                return None;
            }
            scales[t] = 1.0 / c;
            for j in 0..2 {
                alpha[t][j] *= scales[t];
            }
        }
        // Backward
        let mut beta = [1.0_f64; 2];
        let mut gamma = vec![[0.0_f64; 2]; n];
        gamma[n - 1][0] = alpha[n - 1][0];
        gamma[n - 1][1] = alpha[n - 1][1];
        for t in (0..n - 1).rev() {
            let mut next = [0.0_f64; 2];
            for i in 0..2 {
                next[i] = (beta[0] * trans[i][0] * emit(t + 1, 0)
                    + beta[1] * trans[i][1] * emit(t + 1, 1))
                    * scales[t + 1];
            }
            beta = next;
            gamma[t][0] = alpha[t][0] * beta[0];
            gamma[t][1] = alpha[t][1] * beta[1];
            let s = gamma[t][0] + gamma[t][1];
            if s > 0.0 {
                gamma[t][0] /= s;
                gamma[t][1] /= s;
            }
        }
        p_hot_series = gamma.iter().map(|g| g[1]).collect();

        // M-step: re-estimate state means/sds weighted by responsibilities
        for state in 0..2 {
            let w_sum: f64 = gamma.iter().map(|g| g[state]).sum();
            if w_sum < 1e-6 {
                continue;
            }
            let mu = gamma
                .iter()
                .zip(series)
                .map(|(g, x)| g[state] * x)
                .sum::<f64>()
                / w_sum;
            let va = gamma
                .iter()
                .zip(series)
                .map(|(g, x)| g[state] * (x - mu).powi(2))
                .sum::<f64>()
                / w_sum;
            let params = (mu, va.sqrt().clamp(0.3, 10.0));
            if state == 0 {
                normal = params;
            } else {
                hot = params;
            }
        }
        // Enforce ordering: hot >= normal mean
        if hot.0 < normal.0 {
            std::mem::swap(&mut normal, &mut hot);
        }
    }

    let recent_weight = |i: usize| -> f64 { 0.5_f64.powi((n - 1 - i) as i32 / 4) };
    let w_total: f64 = (0..n).map(recent_weight).sum();
    let p_hot = if w_total > 0.0 {
        (0..n)
            .map(|i| recent_weight(i) * p_hot_series[i])
            .sum::<f64>()
            / w_total
    } else {
        0.0
    };

    Some(FormRegime {
        p_hot: p_hot.clamp(0.0, 1.0),
        hot_mean: hot.0,
        normal_mean: normal.0,
        n_games: n,
    })
}

/// Build player_id -> FormRegime from a form CSV (player-match rows, chronological).
pub fn regimes_from_csv(text: &str) -> HashMap<u64, FormRegime> {
    let mut lines = text.lines();
    let header: Vec<String> = lines
        .next()
        .unwrap_or_default()
        .split(',')
        .map(String::from)
        .collect();
    let idx = |name: &str| header.iter().position(|h| h == name).unwrap_or(usize::MAX);

    let (i_pid, i_min, i_shots, i_xg, i_xa, i_date) = (
        idx("player_id"),
        idx("minutes"),
        idx("shots"),
        idx("xg"),
        idx("xa"),
        idx("date"),
    );

    let mut per_player: Vec<(String, u64, f64)> = Vec::new(); // (date, pid, blend)
    for line in lines {
        if line.trim().is_empty() {
            continue;
        }
        let parts: Vec<&str> = line.split(',').collect();
        if parts.len() <= i_date || parts.len() <= i_pid {
            continue;
        }
        let parse = |i: usize| -> f64 { parts.get(i).and_then(|v| v.parse().ok()).unwrap_or(0.0) };
        let minutes = parse(i_min);
        if minutes < 15.0 {
            continue;
        }
        let pid = parts[i_pid].parse::<u64>().unwrap_or(0);
        let blend = blend_per90(
            parse(i_shots) * 90.0 / minutes,
            parse(i_xg) * 90.0 / minutes,
            parse(i_xa) * 90.0 / minutes,
        );
        per_player.push((parts[i_date].to_string(), pid, blend));
    }
    per_player.sort_by(|a, b| a.0.cmp(&b.0));

    let mut by_player: HashMap<u64, Vec<f64>> = HashMap::new();
    for (_, pid, blend) in per_player {
        by_player.entry(pid).or_default().push(blend);
    }

    by_player
        .into_iter()
        .filter_map(|(pid, series)| fit_form_regime(&series).map(|regime| (pid, regime)))
        .collect()
}

#[derive(Debug, Clone, Copy)]
struct RateObservation {
    minutes: f64,
    shots: f64,
    xg: f64,
    xa: f64,
    passes: f64,
    progressive_carries: f64,
}

fn metric_total(observation: RateObservation, metric: u16) -> f64 {
    match metric {
        RATE_SHOT => observation.shots,
        RATE_XG => observation.xg,
        RATE_XA => observation.xa,
        RATE_PASS => observation.passes,
        RATE_PROGC => observation.progressive_carries,
        _ => 0.0,
    }
}

fn rate_features(history: &[RateObservation], metric: u16) -> Option<PlayerRateFeatures> {
    if history.len() < 4 {
        return None;
    }
    let prior_minutes = history.iter().map(|observation| observation.minutes).sum::<f64>();
    if prior_minutes <= 0.0 {
        return None;
    }
    let rates: Vec<f64> = history
        .iter()
        .map(|observation| metric_total(*observation, metric) * 90.0 / observation.minutes.max(1.0))
        .collect();
    if rates.iter().any(|value| !value.is_finite() || *value < 0.0) {
        return None;
    }
    let long_run_per90 = history.iter().map(|observation| metric_total(*observation, metric)).sum::<f64>()
        * 90.0
        / prior_minutes;

    let recent_start = rates.len().saturating_sub(5);
    let recent_rates = &rates[recent_start..];
    let mut recent_numerator = 0.0;
    let mut recent_denominator = 0.0;
    for (index, value) in recent_rates.iter().enumerate() {
        let age = recent_rates.len() - 1 - index;
        let weight = 0.72_f64.powi(age as i32);
        recent_numerator += weight * value;
        recent_denominator += weight;
    }
    let recent_per90 = recent_numerator / recent_denominator.max(f64::EPSILON);

    let trend_start = rates.len().saturating_sub(8);
    let trend_rates = &rates[trend_start..];
    let x_mean = (trend_rates.len().saturating_sub(1) as f64) / 2.0;
    let y_mean = trend_rates.iter().sum::<f64>() / trend_rates.len() as f64;
    let mut covariance = 0.0;
    let mut x_variance = 0.0;
    for (index, value) in trend_rates.iter().enumerate() {
        let x = index as f64 - x_mean;
        covariance += x * (value - y_mean);
        x_variance += x * x;
    }
    let trend_per_match = if x_variance > 0.0 { covariance / x_variance } else { 0.0 };

    let mean = rates.iter().sum::<f64>() / rates.len() as f64;
    let variance_per90 = if rates.len() > 1 {
        rates.iter().map(|value| (value - mean).powi(2)).sum::<f64>() / (rates.len() - 1) as f64
    } else {
        0.0
    };
    Some(PlayerRateFeatures {
        long_run_per90,
        recent_per90,
        trend_per_match,
        variance_per90,
        prior_minutes,
        prior_appearances: history.len() as f64,
    })
}

/// Fit strictly causal pooled next-match rate models inside one fixture cutoff and score every
/// player from the history available immediately before that fixture. Each historical training
/// target is built from features ending before that historical match, so there is no within-file
/// target leakage even though all rows in the file precede the live fixture cutoff.
pub fn learned_rate_forecasts_from_csv(text: &str) -> HashMap<(u64, u16), PlayerRatePrediction> {
    let mut lines = text.lines();
    let header: Vec<String> = lines
        .next()
        .unwrap_or_default()
        .split(',')
        .map(String::from)
        .collect();
    let idx = |name: &str| header.iter().position(|value| value == name);
    let (Some(i_pid), Some(i_date), Some(i_min), Some(i_shots), Some(i_xg), Some(i_xa)) =
        (idx("player_id"), idx("date"), idx("minutes"), idx("shots"), idx("xg"), idx("xa"))
    else {
        return HashMap::new();
    };
    let i_passes = idx("passes");
    let i_prog = idx("prog_carries");

    let mut rows = Vec::<(String, u64, RateObservation)>::new();
    for line in lines {
        if line.trim().is_empty() {
            continue;
        }
        let parts: Vec<&str> = line.split(',').collect();
        let parse = |index: usize| -> f64 {
            parts.get(index).and_then(|value| value.parse::<f64>().ok()).unwrap_or(0.0)
        };
        let Some(player_id) = parts.get(i_pid).and_then(|value| value.parse::<u64>().ok()) else { continue; };
        let Some(date) = parts.get(i_date) else { continue; };
        let minutes = parse(i_min);
        if minutes < 15.0 {
            continue;
        }
        rows.push((
            (*date).to_string(),
            player_id,
            RateObservation {
                minutes,
                shots: parse(i_shots),
                xg: parse(i_xg),
                xa: parse(i_xa),
                passes: i_passes.map(parse).unwrap_or(0.0),
                progressive_carries: i_prog.map(parse).unwrap_or(0.0),
            },
        ));
    }
    rows.sort_by(|left, right| left.0.cmp(&right.0).then_with(|| left.1.cmp(&right.1)));
    let mut by_player = HashMap::<u64, Vec<RateObservation>>::new();
    for (_, player_id, observation) in rows {
        by_player.entry(player_id).or_default().push(observation);
    }

    let mut output = HashMap::new();
    let mut metrics = vec![RATE_SHOT, RATE_XG, RATE_XA];
    if i_passes.is_some() { metrics.push(RATE_PASS); }
    if i_prog.is_some() { metrics.push(RATE_PROGC); }
    for metric in metrics {
        let mut examples = Vec::new();
        for history in by_player.values() {
            for target_index in 4..history.len() {
                let target = history[target_index];
                // Tiny cameos create extreme per-90 labels and should remain usage evidence rather
                // than dominate the rate regression target.
                if target.minutes < 30.0 {
                    continue;
                }
                let Some(features) = rate_features(&history[..target_index], metric) else { continue; };
                let target_per90 = metric_total(target, metric) * 90.0 / target.minutes;
                examples.push(PlayerRateTrainingExample { features, target_per90 });
            }
        }
        if examples.len() < 24 {
            continue;
        }
        let Ok(model) = NextMatchPlayerRateModel::fit(&examples, 2.0) else { continue; };
        for (player_id, history) in &by_player {
            let Some(features) = rate_features(history, metric) else { continue; };
            if let Ok(prediction) = model.predict(features) {
                output.insert((*player_id, metric), prediction);
            }
        }
    }
    output
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn long_series_uses_true_terminal_posterior() {
        let series: Vec<f64> = (0..700)
            .map(|index| if index < 650 { 1.0 + (index % 7) as f64 * 0.01 } else { 3.0 + (index % 5) as f64 * 0.02 })
            .collect();
        let regime = fit_form_regime(&series).expect("long series should fit");
        assert!(regime.p_hot.is_finite());
        assert!((0.0..=1.0).contains(&regime.p_hot));
        assert!(regime.hot_mean >= regime.normal_mean);
    }

    #[test]
    fn csv_parser_keeps_real_shot_signal() {
        let csv = "player_id,name,team,date,minutes,shots,xg,xa,passes\n1,A,T,2026-01-01,90,4,0.7,0.2,32\n1,A,T,2026-01-08,90,3,0.5,0.1,36\n1,A,T,2026-01-15,90,5,0.9,0.3,31\n1,A,T,2026-01-22,90,4,0.8,0.2,39\n";
        let regimes = regimes_from_csv(csv);
        assert!(regimes.contains_key(&1));
    }

    #[test]
    fn sparse_raw_rates_are_shrunk_toward_reference() {
        let sparse = shrunk_player_rate(6.0, 1.25, 30.0);
        let established = shrunk_player_rate(6.0, 1.25, 1_800.0);
        assert!((sparse - 1.25).abs() < 4.75_f64);
        assert!(established > sparse);
        assert!(established < 6.0);
    }

    #[test]
    fn learned_rate_forecast_uses_only_prior_rows_for_training_examples() {
        let mut csv = String::from("player_id,name,team,date,minutes,shots,xg,xa,passes,prog_carries\n");
        for player in 1..=8_u64 {
            for game in 0..10_u32 {
                let shots = 1.0 + (player % 4) as f64 + game as f64 * 0.08;
                let xa = 0.05 * (player % 3) as f64 + game as f64 * 0.005;
                let carries = (player % 5) as f64 + game as f64 * 0.1;
                csv.push_str(&format!(
                    "{player},P,T,2026-01-{day:02},90,{shots},0.2,{xa},35,{carries}\n",
                    day = game + 1,
                ));
            }
        }
        let forecasts = learned_rate_forecasts_from_csv(&csv);
        assert!(forecasts.contains_key(&(1, RATE_SHOT)));
        assert!(forecasts.contains_key(&(1, RATE_XG)));
        assert!(forecasts.contains_key(&(1, RATE_XA)));
        assert!(forecasts.contains_key(&(1, RATE_PASS)));
        assert!(forecasts.get(&(1, RATE_SHOT)).unwrap().mean_per90 >= 0.0);
    }

    #[test]
    fn participation_fit_excludes_target_and_future_rows() {
        let mut tsv = String::from(
            "date\tmatch_id\tteam_id\tteam\tplayer_id\tclub_fixtures\tprior_listings\tprior_appearances\tprior_starts\tprior_minutes\tprior_start_minutes\tdays_since_last_appearance\tdays_since_last_listed\tappeared\tstarted\tminutes\n",
        );
        for index in 0..120_u64 {
            let started = index % 3 == 0;
            let appeared = started || index % 4 != 0;
            tsv.push_str(&format!(
                "2026-01-01\t{}\t1\tT\t{}\t12\t11\t9\t6\t600\t450\t7\t3\t{}\t{}\t{}\n",
                1000 + index,
                index + 1,
                u8::from(appeared),
                u8::from(started),
                if started { 75 } else if appeared { 20 } else { 0 },
            ));
        }
        for index in 0..20_u64 {
            tsv.push_str(&format!(
                "2026-03-01\t{}\t1\tT\t{}\t12\t11\t9\t6\t600\t450\t7\t3\t1\t1\t90\n",
                5000 + index,
                500 + index,
            ));
        }
        let cutoff = Date::from_ymd(2026, 2, 1).unwrap();
        let model = learned_participation_model_from_tsv(&tsv, cutoff).unwrap();
        assert_eq!(model.observations(), 120);
    }
}
