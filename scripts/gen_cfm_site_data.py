#!/usr/bin/env python3
"""Emit the CFM scout top-20 as a typed TS data module for footy-site.

Reads the final data/cfm_scout_top20.csv + /tmp/cfm_per.json (psych profiles
and rationales) and writes /home/drewclaw/footy-site/src/cfmData.ts.
No em dashes in copy: ':' and commas only.
"""
import json
import pandas as pd

t = pd.read_csv("/home/drewclaw/footy-models/data/cfm_scout_top20.csv")
per = {int(k): v for k, v in json.load(open("/tmp/cfm_per.json")).items()}

def noemd(s):
    return str(s).replace("—", ": ").replace("–", "-").replace("\u2014", ": ")

rows = []
for _, r in t.iterrows():
    pid = int(r["player_id"])
    p = per[pid]
    rank = int(r["rank"])
    top = [f"{k} {v:.0f}" for k, v in p["toppsych"].items()]
    rationale = noemd(p.get("rationale", ""))
    rows.append({
        "rank": rank,
        "name": r["name"], "club": r["club"], "league": r["competition"], "country": r["country"],
        "pos": r["pos_cls"], "age": round(float(r["age"]), 2),
        "mv": int(r["current_mv"]), "ca": int(r["fm_ca"]), "pa": int(r["fm_pa"]),
        "psychFit": round(float(r["psych_fit"]), 3),
        "tail": round(float(r["tail_score"]), 3),
        "yield12m": round(float(r["yield_12m_pct"]), 1),
        "squadGap": str(r["squad_gap_filled"]), "squadFit": int(r["squad_fit"]),
        "sRating": ("" if pd.isna(r["sofascore_rating"]) else round(float(r["sofascore_rating"]), 2)),
        "sGoals": ("" if isinstance(r["sofascore_goals"], str) else int(r["sofascore_goals"])),
        "sAssists": r["sofascore_assists"],
        "sApps": ("" if isinstance(r["sofascore_appearances"], str) else int(r["sofascore_appearances"])),
        "sTournament": str(r["sofascore_tournament"]), "sSeason": str(r["sofascore_season"]),
        "sConfidence": str(r["sofascore_confidence"]),
        "topPsych": top,
        "mcMedian": int(r["median_36m"]), "mcP10": int(r["p10"]), "mcP90": int(r["p90"]),
        "p15x": round(float(r["p15x"]), 3), "p2x": round(float(r["p2x"]), 3),
        "p3x": round(float(r["p3x"]), 3), "downside": round(float(r["downside_prob"]), 3),
        "baseMedian": int(r["mc_median_base"]),
        "rationale": rationale,
        "chart": f"/cfm/charts/chart_player_{rank:02d}.png",
        "chartBase": f"/cfm/charts_base/chart_player_{rank:02d}.png",
    })

lines = []
lines.append("// Generated by scripts/gen_cfm_site_data.py. Do not edit by hand.")
lines.append("// CF Montréal scout top-20 (STEERING_CFM.md). MC numbers are the spike run")
lines.append("// (drift = v3 expectile-0.9 tail score), seed 42, 1000 paths, annual vol 0.4688.")
lines.append("")
lines.append("export type CFMPlayer = {")
fields = ["rank: number", "name: string", "club: string", "league: string", "country: string",
          "pos: string", "age: number", "mv: number", "ca: number", "pa: number",
          "psychFit: number", "tail: number", "yield12m: number", "squadGap: string", "squadFit: number",
          "sRating: number | string", "sGoals: number | string", "sAssists: number | string",
          "sApps: number | string", "sTournament: string", "sSeason: string", "sConfidence: string",
          "topPsych: string[]", "mcMedian: number", "mcP10: number", "mcP90: number",
          "p15x: number", "p2x: number", "p3x: number", "downside: number", "baseMedian: number",
          "rationale: string", "chart: string", "chartBase: string"]
for f in fields:
    lines.append(f"  {f};")
lines.append("};")
lines.append("")

def js(v):
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, list):
        return "[" + ", ".join(js(x) for x in v) + "]"
    return json.dumps(v)

lines.append("export const CFM_PLAYERS: CFMPlayer[] = [")
for row in rows:
    lines.append("  {" + ", ".join(f"{k}: {js(v)}" for k, v in row.items()) + "},")
lines.append("];")
lines.append("")

out = "\n".join(lines)
with open("/home/drewclaw/footy-site/src/cfmData.ts", "w") as f:
    f.write(out)
print("wrote /home/drewclaw/footy-site/src/cfmData.ts", len(rows), "players")
print("em dashes in copy:", out.count("\u2014"))
